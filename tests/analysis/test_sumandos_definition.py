import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
for _p in (str(ROOT / "index-deconvolution" / "src"), str(ROOT)):
    if _p not in sys.path:
        sys.path.insert(0, _p)


# ---------------------------------------------------------------------------
# ARM 1 — Rule 110, the standing counterexample
# ---------------------------------------------------------------------------

def _rule110_column() -> list[int]:
    """Rule 110 as a truth table over 3 inputs, LSB-first (left, centre, right).

    Wolfram numbering: the output for neighbourhood (l, c, r) read as the binary
    number lcr is bit (4l + 2c + r) of 110. Written out rather than imported so
    this test does not depend on the module it is guarding.
    """
    col = []
    for x in range(8):
        left = (x >> 2) & 1
        centre = (x >> 1) & 1
        right = x & 1
        col.append((110 >> (4 * left + 2 * centre + right)) & 1)
    return col


def test_rule110_has_no_free_coordinates_yet_does_compress():
    """The whole ruling in one case.

    All three inputs are connected, so the free coordinates are EMPTY. Under the
    forbidden reading Omega = {0}: no sumandos, no compression, and L must list
    every minterm. Under the correct reading Rule 110 is a small number of
    schemata whose don't-cares sit ON CONNECTED INPUTS.

    If the count of schemata ever equals the count of minterms, the compression
    has vanished and the forbidden reading has silently won.
    """
    from deconvolution import essential_variables, minimal_dnf, reduce_column

    col = _rule110_column()
    n = 3
    ess = essential_variables(col, n)
    assert ess == [0, 1, 2], (
        f"Rule 110 must depend on all three inputs; got {ess}. If this fails the "
        "counterexample is broken, not the ruling.")

    free = [i for i in range(n) if i not in set(ess)]
    assert free == [], "Rule 110 has NO free coordinates -- that is the point"

    reduced = reduce_column(col, n, ess)
    minterms = sum(reduced)
    schemata = minimal_dnf(reduced)

    assert minterms == 5, f"Rule 110 has five minterms; got {minterms}"
    assert len(schemata) < minterms, (
        f"Rule 110 compressed to {len(schemata)} schemata from {minterms} "
        f"minterms. With NO free coordinates, every bit of that compression "
        f"comes from don't-cares on CONNECTED inputs -- which the reading "
        f"'sumandos = disconnected coordinates' cannot express at all.")

    # And the don't-cares really are on connected inputs.
    dont_cares = [n - len(s["activators"]) - len(s["inhibitors"]) for s in schemata]
    assert any(d > 0 for d in dont_cares), (
        "no schema has a don't-care, so there is nothing for the sumandos to "
        "fill and the counterexample has stopped counter-exemplifying")


def test_or_and_xor_of_equal_in_degree_are_separated():
    """The quantitative half of the ruling (GLOSSARY sec.1d).

    The narrow reading sees compression only from disconnected coordinates, so
    it cannot tell an OR from an XOR of the same in-degree -- both are "one gate
    with n-d free coordinates". The general reading separates them exactly.

    Uses in-degree 6 rather than the glossary's 10 to keep the test quick; the
    property is the same and the numbers are recomputed here, not quoted.
    """
    from deconvolution import minimal_dnf

    d = 6
    or_col = [1 if x != 0 else 0 for x in range(2 ** d)]
    xor_col = [bin(x).count("1") % 2 for x in range(2 ** d)]

    or_schemata = len(minimal_dnf(or_col))
    xor_schemata = len(minimal_dnf(xor_col))
    xor_minterms = sum(xor_col)

    assert or_schemata == d, (
        f"an OR of in-degree {d} covers {sum(or_col)} minterms with {d} "
        f"schemata; got {or_schemata}")
    assert xor_schemata == xor_minterms, (
        f"an XOR of in-degree {d} has no mergeable minterms, so it needs one "
        f"schema each: expected {xor_minterms}, got {xor_schemata}")
    assert or_schemata != xor_schemata, (
        "OR and XOR of the same in-degree got the same schema count, so the "
        "measure has collapsed to the narrow reading and is blind to the "
        "distinction the general one makes")


