"""The sumandos are NOT "the disconnected coordinates". Guarded, because prose lost.

GOVERNANCE/GLOSSARY.md sec.1d, author ruling 2026-09-03:

    Definition. The sumandos of a schema are the fillings of ITS OWN DON'T-CARE
    POSITIONS, wherever those positions fall. Omega is the offset family they
    generate.

    Permitted: "the disconnected coordinates are free in every schema, and are
    the special case always present."
    FORBIDDEN: anything of the form "the sumandos are / correspond to / are
    generated by the coordinates that do not feed the node", stated as the
    definition.

WHY THIS IS A TEST AND NOT A PARAGRAPH.

The glossary records that this was settled and re-adopted FOUR times, each
recurrence costing a long conversation. It recurred a FIFTH time on 2026-09-07,
in a session whose whole subject was auditing this repository -- and the wrong
reading was sitting in the docstring of the method's OWNER
(index-deconvolution/src/deconvolution.py) the entire time, saying "the
remaining bits are the FREE COORDINATES; their subset sums are the sumandos".

A ruling that lives only in prose is re-litigated whenever someone reads the
code instead of the glossary. The cause is always the same and the glossary
names it: a reader meets a helper computing Complement[Range[n], connected] and
promotes that implementation detail into the definition. So the definition gets
a gate.

ARM 1 is executable: Rule 110 is the standing counterexample, and it either
behaves as the ruling says or it does not.

ARM 2 is a text scan over the trees this repository owns, for the forbidden
phrasing. It is not a substitute for arm 1 -- it is what stops the sentence
being written again.
"""
from __future__ import annotations

