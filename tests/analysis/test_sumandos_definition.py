# ARM 2 — the sentence must not be written again
# ---------------------------------------------------------------------------

FORBIDDEN = re.compile(
    r"sumandos?\s+(?:are|is|=|:)?\s*(?:the\s+)?(?:disconnected|unconnected)\b"
    r"|(?:disconnected|unconnected)\s+(?:nodes?|coordinates?|inputs?|bits?)\s+"
    r"(?:are|as|=)\s+(?:the\s+)?sumandos?"
    r"|their\s+subset\s+sums\s+are\s+the\s+sumandos"
    r"|free\s+coordinates?['’]?s?\s+(?:decimal\s+)?encoding\s+is\s+the\s+.?sumandos"
    r"|sumandos?\s*\(\s*the\s+free\s+(?:offset\s+)?dimension\s*\)",
    re.IGNORECASE)

# Trees this repository owns. Replication packages and provenance archives are
# excluded: imp-pathinfo's published tables and the doc/ chat transcripts are
# records of what was written at the time, and rewriting a record is not a fix.
OWNED = ("src", "index-deconvolution/src", "index-deconvolution/level3",
         "index-deconvolution/experiments", "tools", "tests")

# Declared exceptions: text that QUOTES the forbidden phrasing in order to
# forbid it. Each must actually be doing that.
QUOTING_THE_ERROR = {
    "tests/analysis/test_sumandos_definition.py",
    "index-deconvolution/src/deconvolution.py",
    "index-deconvolution/level3/behaviour_table.py",
    "index-deconvolution/experiments/exp01_pivots_sumandos.py",
}


# Extensions, not just .py. The first plant of this guard was written into a
# .sh file and slipped straight through, which is the comfortable-denominator
# failure in miniature: a scan that covers one file type reports clean over the
# types it cannot see.
SCANNED_SUFFIXES = (".py", ".m", ".wl", ".sh", ".md")


def _owned_files() -> list[Path]:
    out: list[Path] = []
    for d in OWNED:
        base = ROOT / d
        if not base.is_dir():
            continue
        for p in base.rglob("*"):
            if p.is_file() and p.suffix in SCANNED_SUFFIXES \
                    and "__pycache__" not in p.parts:
                out.append(p)
    return out


def test_the_forbidden_definition_is_not_written_anywhere_we_own():
    files = _owned_files()
    assert files, "REFUSED: scanned 0 files"
    offenders = []
    for p in files:
        rel = str(p.relative_to(ROOT))
        if rel in QUOTING_THE_ERROR:
            continue
        for i, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            if FORBIDDEN.search(line):
                offenders.append(f"{rel}:{i}: {line.strip()[:100]}")
    assert not offenders, (
        f"the forbidden definition of `sumandos` is written in {len(offenders)} "
        f"place(s), over {len(files)} files scanned:\n  " + "\n  ".join(offenders) +
        "\n\nGLOSSARY sec.1d: the sumandos of a schema are the fillings of its "
        "OWN don't-care positions, wherever they fall. The disconnected "
        "coordinates are the special case, and may be illustrated but never "
        "defined as the general object."
    )


