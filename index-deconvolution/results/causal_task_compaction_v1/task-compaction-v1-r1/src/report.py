"""task-compaction-v1-r1 -- presentation only: tables from saved artifacts.

Reads production/ and audit/ JSON; imports no model, minimizer, producer or audit code and
writes no evidence. Post-freeze presentation code; it cannot alter any measured field.
Usage: python report.py <production dir> <audit dir> <out.md>
"""
from __future__ import annotations

import json
import os
import sys


def cell(prod, cid):
    return json.load(open(os.path.join(prod, "cells", f"cell_{cid:02d}.json")))


def frac(f):
    return f"{f['num']}/{f['den']}"


def main(prod, aud, out):
    if os.path.exists(out):
        print(f"refusing: {out} exists")
        return 2
    s = json.load(open(os.path.join(prod, "summary.json")))
    a = json.load(open(os.path.join(aud, "audit.json")))
    L = [f"<!-- generated by src/report.py from {os.path.basename(prod)}/ and {os.path.basename(aud)}/; "
         "do not edit by hand -->", "",
         f"Audit status: **{a['status']}** (invalid {a['n_invalid']}, missing {a['n_missing']}).", "",
         "## Per-cell outcomes (24 cells; INTERVENTION = primary, AUTO = control)", "",
         "| id | model | task | regime | \\|Q\\| | N=\\|X\\| | K0 | K* | K*/N | n-ceil(log2 K*) | strict rounds | outcome "
         "| P0 closed | best old (id, family, K) | best non-control | comparison | sufficient raw/distinct |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in s["cells"]:
        cc, d = c["candidates"], c["cell"]
        b, nc = cc["best"], cc["best_lossless_control_excluded"]
        L.append(f"| {d['cell_id']} | {d['model']} | {d['task']} | {d['regime']} | {d['n_actions']} | {c['N']} | "
                 f"{c['K0']} | {c['K_star']} | {frac(c['K_star_over_N'])} | {c['capacity_saving_bits']} | "
                 f"{c['strict_rounds']} | {c['outcome']} | {c['baselines']['output_partition_P0']['closed']} | "
                 f"({b['candidate_id']}, {b['family']}, {b['K']}) | "
                 f"{'null' if nc is None else '(%d, %s, %d)' % (nc['candidate_id'], nc['family'], nc['K'])} | "
                 f"{cc['comparison']} | {cc['sufficient_raw']}/{cc['sufficient_distinct']} |")
    for reg in ("INTERVENTION", "AUTO"):
        cs = [c for c in s["cells"] if c["cell"]["regime"] == reg]
        L += ["", f"**{reg}** ({len(cs)} cells): "
              f"EXACT_REDUCTION {sum(c['outcome'] == 'EXACT_REDUCTION' for c in cs)}, "
              f"NO_REDUCTION {sum(c['outcome'] == 'NO_REDUCTION' for c in cs)}; "
              f"MATCHES_OPTIMUM {sum(c['candidates']['comparison'] == 'MATCHES_OPTIMUM' for c in cs)}, "
              f"CANDIDATE_GAP {sum(c['candidates']['comparison'] == 'CANDIDATE_GAP' for c in cs)}."]
    L += ["", "## Candidate decisions (all 3,276 records)", "",
          "| regime | records | decodable | closed | sufficient | sufficient & identical to alpha* |", "|---|---|---|---|---|---|"]
    for reg in ("INTERVENTION", "AUTO"):
        cs = [c["candidates"] for c in s["cells"] if c["cell"]["regime"] == reg]
        L.append(f"| {reg} | {sum(c['raw'] for c in cs)} | {sum(c['decodable_raw'] for c in cs)} | "
                 f"{sum(c['closed_raw'] for c in cs)} | {sum(c['sufficient_raw'] for c in cs)} | "
                 f"{sum(c['matching_optimum_raw'] for c in cs)} |")
    L += ["", "## Storage entries NOT counted in the capacity number (per cell)", "",
          "| id | state-to-group map | decoder | macro tables | action labels | micro action tables |", "|---|---|---|---|---|---|"]
    for c in s["cells"]:
        e = c["storage_entries_excluded_from_capacity"]
        L.append(f"| {c['cell']['cell_id']} | {e['state_to_group_map']} | {e['decoder']} | "
                 f"{e['macro_transition_tables']} | {e['action_labels']} | {e['micro_action_tables']} |")
    L += ["", "## Worked examples: TP (parity) under INTERVENTION, one per model (not selected by outcome)", ""]
    for c in s["cells"]:
        d = c["cell"]
        if (d["task"], d["regime"]) != ("TP", "INTERVENTION"):
            continue
        art = cell(prod, d["cell_id"])
        counts = [max(v) + 1 for v in art["stages"]]
        L += [f"### {d['model']} (cell {d['cell_id']}), h(x) = popcount(x) mod 2, |Q| = {d['n_actions']}", "",
              f"- K0 = {c['K0']}, K* = {c['K_star']} of N = {c['N']} ({c['outcome']}); strict rounds = "
              f"{c['strict_rounds']}.",
              "- Refinement chain (blocks per stage; last entry is the first repeated vector): "
              + " -> ".join(f"P{i}:{k}" for i, k in enumerate(counts)) + "."]
        for w in art["witnesses"]:
            L.append(f"- Round {w['round']} witness: x={w['x']}, y={w['y']} share P{w['round']} and split in "
                     f"P{w['round'] + 1}; word {w['word_names']} (indices {w['word']}); states x {w['path_x']} / "
                     f"y {w['path_y']}; outputs x {w['outputs_x']} / y {w['outputs_y']}.")
        if not art["witnesses"]:
            L.append("- No strict round: P0 is already closed under every action (stable at depth 0).")
        b = c["candidates"]["best"]
        L += [f"- Best old candidate: id {b['candidate_id']} ({b['family']}), K = {b['K']}, "
              f"K - K* = {b['K_minus_Kstar']} -> {c['candidates']['comparison']}; sufficient candidates "
              f"{c['candidates']['sufficient_raw']} raw / {c['candidates']['sufficient_distinct']} distinct "
              f"partitions out of {c['candidates']['raw']} raw / {c['candidates']['distinct_partitions']} distinct.", ""]
    L += ["## Refinement chains of every cell (blocks per stage)", ""]
    for c in s["cells"]:
        art = cell(prod, c["cell"]["cell_id"])
        L.append(f"- cell {c['cell']['cell_id']} {c['cell']['model']}/{c['cell']['task']}/{c['cell']['regime']}: "
                 + " -> ".join(str(max(v) + 1) for v in art["stages"]))
    with open(out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:4]))
